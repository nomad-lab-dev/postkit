// MARK: - PostKit
// GeneratedPost.swift — GeneratedPost SwiftData model and related types

import Foundation
import os
import SwiftData
import SwiftUI

private let modelLogger = Logger(subsystem: "PostKit", category: "Models")

enum SocialPlatform: String, Codable, CaseIterable, Sendable {
    case instagram, tiktok, twitter, linkedin, reddit, pinterest

    var displayName: String {
        switch self {
        case .twitter: "X"
        default: rawValue.capitalized
        }
    }

    var icon: String {
        switch self {
        case .instagram: "camera.fill"
        case .tiktok: "play.rectangle.fill"
        case .twitter: "at"
        case .linkedin: "briefcase.fill"
        case .reddit: "bubble.left.fill"
        case .pinterest: "pin.fill"
        }
    }

    var characterLimit: Int {
        switch self {
        case .instagram: 2200
        case .tiktok: 2200
        case .twitter: 280
        case .linkedin: 3000
        case .reddit: 40000
        case .pinterest: 500
        }
    }
}

enum PostStatus: String, Codable, CaseIterable, Sendable {
    case draft, ready, published

    var displayName: LocalizedStringKey {
        switch self {
        case .draft: "Draft"
        case .ready: "Ready"
        case .published: "Published"
        }
    }
}

@Model
final class GeneratedPost {
    var id: UUID
    var title: String = ""
    var pillarID: UUID
    var templateID: UUID?
    var photoIDsData: Data?
    var caption: String = ""
    var hashtagsData: Data?
    var platformRaw: String = SocialPlatform.instagram.rawValue
    var statusRaw: String = PostStatus.draft.rawValue
    var isAutoGenerated: Bool = false
    var scheduleData: Data?
    var createdAt: Date

    var photoIDs: [String] {
        get {
            guard let data = photoIDsData else { return [] }
            do { return try JSONDecoder().decode([String].self, from: data) }
            catch { modelLogger.error("GeneratedPost.photoIDs decode failed: \(error)"); return [] }
        }
        set {
            photoIDsData = try? JSONEncoder().encode(newValue)
        }
    }

    var hashtags: [String] {
        get {
            guard let data = hashtagsData else { return [] }
            do { return try JSONDecoder().decode([String].self, from: data) }
            catch { modelLogger.error("GeneratedPost.hashtags decode failed: \(error)"); return [] }
        }
        set {
            hashtagsData = try? JSONEncoder().encode(newValue)
        }
    }

    var platform: SocialPlatform {
        get { SocialPlatform(rawValue: platformRaw) ?? .instagram }
        set { platformRaw = newValue.rawValue }
    }

    var status: PostStatus {
        get { PostStatus(rawValue: statusRaw) ?? .draft }
        set { statusRaw = newValue.rawValue }
    }

    var schedule: TemplateSchedule {
        get {
            guard let data = scheduleData else { return TemplateSchedule() }
            return (try? JSONDecoder().decode(TemplateSchedule.self, from: data)) ?? TemplateSchedule()
        }
        set {
            scheduleData = try? JSONEncoder().encode(newValue)
        }
    }

    init(
        title: String = "",
        pillarID: UUID,
        templateID: UUID? = nil,
        photoIDs: [String] = [],
        caption: String = "",
        hashtags: [String] = [],
        platform: SocialPlatform = .instagram,
        status: PostStatus = .draft,
        isAutoGenerated: Bool = false,
        schedule: TemplateSchedule = TemplateSchedule(),
        createdAt: Date = .now
    ) {
        self.id = UUID()
        self.title = title
        self.pillarID = pillarID
        self.templateID = templateID
        self.photoIDsData = try? JSONEncoder().encode(photoIDs)
        self.caption = caption
        self.hashtagsData = try? JSONEncoder().encode(hashtags)
        self.platformRaw = platform.rawValue
        self.statusRaw = status.rawValue
        self.isAutoGenerated = isAutoGenerated
        self.scheduleData = try? JSONEncoder().encode(schedule)
        self.createdAt = createdAt
    }
}
