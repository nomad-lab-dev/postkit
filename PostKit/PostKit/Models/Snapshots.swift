struct GeneratedPostSnapshot: Equatable, Identifiable, Sendable {
    let id: UUID
    var title: String
    var pillarID: UUID
    var templateID: UUID?
    var photoIDs: [String]
    var caption: String
    var hashtags: [String]
    var platform: SocialPlatform
    var status: PostStatus
    var isAutoGenerated: Bool
    var schedule: TemplateSchedule
    var createdAt: Date

    init(
        id: UUID = UUID(),
        title: String = "",
        pillarID: UUID,
        templateID: UUID? = nil,
        photoIDs: [String] = [],
        caption: String = "",
        hashtags: [String] = [],
        platform: SocialPlatform = .instagram,
        status: PostStatus = .draft,
        isAutoGenerated: Bool = false,
        schedule: TemplateSchedule = TemplateSchedule(),
        createdAt: Date = .now
    ) {
        self.id = id
        self.title = title
        self.pillarID = pillarID
        self.templateID = templateID
        self.photoIDs = photoIDs
        self.caption = caption
        self.hashtags = hashtags
        self.platform = platform
        self.status = status
        self.isAutoGenerated = isAutoGenerated
        self.schedule = schedule
        self.createdAt = createdAt
    }

    init(_ post: GeneratedPost) {
        self.id = post.id
        self.title = post.title
        self.pillarID = post.pillarID
        self.templateID = post.templateID
        self.photoIDs = post.photoIDs
        self.caption = post.caption
        self.hashtags = post.hashtags
        self.platform = post.platform
        self.status = post.status
        self.isAutoGenerated = post.isAutoGenerated
        self.schedule = post.schedule
        self.createdAt = post.createdAt
    }
}

struct TemplateSnapshot: Equatable, Identifiable, Sendable {
    let id: UUID
    var name: String
    var about: String
    var slots: [TemplateSlotData]
    var locations: [String]
    var schedule: TemplateSchedule
    var lastPostedAt: Date?
    var createdAt: Date

    init(
        id: UUID = UUID(),
        name: String,
        about: String = "",
        slots: [TemplateSlotData] = [],
        locations: [String] = [],
        schedule: TemplateSchedule = TemplateSchedule(),
        lastPostedAt: Date? = nil,
        createdAt: Date = .now
    ) {
        self.id = id
        self.name = name
        self.about = about
        self.slots = slots
        self.locations = locations
        self.schedule = schedule
        self.lastPostedAt = lastPostedAt
        self.createdAt = createdAt
    }

    init(_ template: PostTemplate) {
        self.id = template.id
        self.name = template.name
        self.about = template.about
        self.slots = template.slots
        self.locations = template.locations
        self.schedule = template.schedule
        self.lastPostedAt = template.lastPostedAt
        self.createdAt = template.createdAt
    }
}
