// MARK: - PostKit
// Snapshots.swift — Value-type snapshots for pillars, photos, posts, and templates

import Foundation

struct PillarSnapshot: Equatable, Identifiable, Sendable {
    let id: UUID
    var name: String
    var emoji: String
    var about: String
    var tone: PillarTone
    var topics: [String]
    var referenceTags: [String]
    var referencePhotoIDs: [String]
    var photoCount: Int
    var postsPerWeek: Int
    var colorHex: String
    var topPhotoAssetIDs: [String]

    init(
        id: UUID = UUID(),
        name: String,
        emoji: String,
        about: String = "",
        tone: PillarTone = .casual,
        topics: [String] = [],
        referenceTags: [String] = [],
        referencePhotoIDs: [String] = [],
        colorHex: String = "#8b5cf6",
        photoCount: Int = 0,
        postsPerWeek: Int = 3,
        topPhotoAssetIDs: [String] = []
    ) {
        self.id = id
        self.name = name
        self.emoji = emoji
        self.about = about
        self.tone = tone
        self.topics = topics
        self.referenceTags = referenceTags
        self.referencePhotoIDs = referencePhotoIDs
        self.colorHex = colorHex
        self.photoCount = photoCount
        self.postsPerWeek = postsPerWeek
        self.topPhotoAssetIDs = topPhotoAssetIDs
    }

    init(_ pillar: Pillar, photoCount: Int = 0) {
        self.id = pillar.id
        self.name = pillar.name
        self.emoji = pillar.emoji
        self.about = pillar.about
        self.tone = pillar.tone
        self.topics = pillar.topics
        self.referenceTags = pillar.referenceTags
        self.referencePhotoIDs = pillar.referencePhotoIDs
        self.photoCount = photoCount
        self.postsPerWeek = pillar.postsPerWeek
        self.colorHex = pillar.colorHex
        self.topPhotoAssetIDs = []
    }
}

